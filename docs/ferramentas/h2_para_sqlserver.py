"""Gera as migrações do SQL Server (Azure SQL) a partir das migrações do H2.

As migrações do H2 são a fonte; as do SQL Server são geradas por este script para as duas
versões nunca saírem de sincronia. Rode da raiz do repositório depois de mudar qualquer .sql do H2:

    python docs/ferramentas/h2_para_sqlserver.py

Conversões:
    BIGINT GENERATED BY DEFAULT AS IDENTITY -> BIGINT IDENTITY(1,1)
    BOOLEAN -> BIT · TRUE/FALSE -> 1/0
    TIMESTAMP -> DATETIME2 · LOCALTIMESTAMP -> SYSUTCDATETIME() (datas em UTC)
    DOUBLE PRECISION -> FLOAT
    INSERT com id explícito -> envolto em SET IDENTITY_INSERT <tabela> ON/OFF
    ALTER TABLE t ALTER COLUMN id RESTART WITH n -> DBCC CHECKIDENT ('t', RESEED, n - 1) WITH NO_INFOMSGS

Textos continuam VARCHAR: o banco é criado com a collation UTF-8 (Latin1_General_100_CI_AS_SC_UTF8),
então acentos e qualquer caractere Unicode são gravados sem perda e o Hibernate valida o schema sem ajustes.
"""
import re
from pathlib import Path

RAIZ = Path(__file__).resolve().parents[2]
RECURSOS = RAIZ / "src" / "main" / "resources" / "db"
ARQUIVOS = [
    ("migration/h2/V1__schema.sql", "migration/sqlserver/V1__schema.sql"),
    ("migration/h2/V2__dados_iniciais.sql", "migration/sqlserver/V2__dados_iniciais.sql"),
    ("demo/h2/V2_1__historico_demo.sql", "demo/sqlserver/V2_1__historico_demo.sql"),
]
AVISO = "-- GERADO por docs/ferramentas/h2_para_sqlserver.py a partir de {origem}. Não edite à mão.\n"

# Valem no código e nos comentários (para os comentários continuarem verdadeiros).
TIPOS = [
    (re.compile(r"\bBIGINT GENERATED BY DEFAULT AS IDENTITY\b"), "BIGINT IDENTITY(1,1)"),
    (re.compile(r"\bBOOLEAN\b"), "BIT"),
    (re.compile(r"\bDOUBLE PRECISION\b"), "FLOAT"),
    (re.compile(r"\bTIMESTAMP\b"), "DATETIME2"),
    (re.compile(r"\bLOCALTIMESTAMP\b"), "SYSUTCDATETIME()"),
    (re.compile(r"\(H2, SQL padrão\)"), "(SQL Server / Azure SQL)"),
]
# Só no código (fora de textos e comentários).
LITERAIS = [
    (re.compile(r"\bTRUE\b"), "1"),
    (re.compile(r"\bFALSE\b"), "0"),
]
RESTART = re.compile(r"^ALTER TABLE (\w+) ALTER COLUMN id RESTART WITH (\d+)$", re.IGNORECASE)
INSERT_COM_ID = re.compile(r"^INSERT INTO (\w+)\s*\(\s*id\s*,", re.IGNORECASE)


def partes(sql):
    """Divide o SQL em trechos (tipo, texto): 'codigo', 'texto' ('...') ou 'comentario' (-- até o fim da linha)."""
    i, ini, n, saida = 0, 0, len(sql), []
    while i < n:
        if sql.startswith("--", i):
            saida.append(("codigo", sql[ini:i]))
            fim = sql.find("\n", i)
            fim = n if fim == -1 else fim
            saida.append(("comentario", sql[i:fim]))
            i = ini = fim
        elif sql[i] == "'":
            saida.append(("codigo", sql[ini:i]))
            j = i + 1
            while j < n:
                if sql[j] == "'" and j + 1 < n and sql[j + 1] == "'":
                    j += 2
                elif sql[j] == "'":
                    break
                else:
                    j += 1
            saida.append(("texto", sql[i:j + 1]))
            i = ini = j + 1
        else:
            i += 1
    saida.append(("codigo", sql[ini:]))
    return [p for p in saida if p[1]]


def converter_trechos(sql):
    resultado = []
    for tipo, txt in partes(sql):
        if tipo != "texto":
            for regex, novo in TIPOS:
                txt = regex.sub(novo, txt)
        if tipo == "codigo":
            for regex, novo in LITERAIS:
                txt = regex.sub(novo, txt)
        resultado.append(txt)
    return "".join(resultado)


def comandos(sql):
    """Divide em comandos terminados por ';' (fora de textos e comentários), mantendo comentários e espaços."""
    atual, saida = [], []
    for tipo, txt in partes(sql):
        if tipo != "codigo":
            atual.append(txt)
            continue
        pedacos = txt.split(";")
        for k, pedaco in enumerate(pedacos):
            atual.append(pedaco)
            if k < len(pedacos) - 1:
                saida.append(("".join(atual), True))
                atual = []
    saida.append(("".join(atual), False))
    return saida


def sem_comentarios(cmd):
    return "".join(t for tipo, t in partes(cmd) if tipo != "comentario").strip()


def converter(sql):
    saida = []
    for cmd, terminado in comandos(converter_trechos(sql)):
        if not terminado:
            saida.append(cmd)
            continue
        corpo = sem_comentarios(cmd)
        # Onde o comando começa (depois dos comentários e linhas em branco que o antecedem).
        inicio = re.search(r"(?m)^(?![ \t]*--)[ \t]*\S", cmd)
        inicio = inicio.end() - 1 if inicio else 0
        antes = cmd[:inicio]
        m = RESTART.match(corpo)
        if m:
            # Com linhas na tabela, o próximo id gerado é o valor do RESEED + 1.
            saida.append(f"{antes}DBCC CHECKIDENT ('{m.group(1)}', RESEED, {int(m.group(2)) - 1}) WITH NO_INFOMSGS;")
            continue
        m = INSERT_COM_ID.match(corpo)
        if m:
            saida.append(f"{antes}SET IDENTITY_INSERT {m.group(1)} ON;\n{cmd[inicio:]};\n"
                         f"SET IDENTITY_INSERT {m.group(1)} OFF;")
            continue
        saida.append(cmd + ";")
    return "".join(saida)


def main():
    for origem, destino in ARQUIVOS:
        texto = (RECURSOS / origem).read_text(encoding="utf-8")
        alvo = RECURSOS / destino
        alvo.parent.mkdir(parents=True, exist_ok=True)
        alvo.write_text(AVISO.format(origem=f"db/{origem}") + converter(texto), encoding="utf-8", newline="\n")
        print(f"db/{destino}")


if __name__ == "__main__":
    main()
